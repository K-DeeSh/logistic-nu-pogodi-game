export function pickWeightedRandom(
  defs: ItemDefinition[],
  extraWeights?: Record<string, number>
): ItemDefinition {
  const weighted = defs.map((d) => ({
    def: d,
    w: d.weight + (extraWeights?.[d.id] ?? 0),
  }));
  const total = weighted.reduce((s, x) => s + Math.max(0, x.w), 0);
  let r = Math.random() * total;
  for (const { def, w } of weighted) {
    r -= Math.max(0, w);
    if (r <= 0) return def;
  }
  return defs[defs.length - 1];
}
